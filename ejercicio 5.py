#Cree un programa en python que pida al usuario ingresar su edad por teclado y 
# determine mediante una estructura condicional si es mayor de edad (18 años o mas) o menor de edad

edad = int(input("Ingresar la edad del usuario: "))

if edad >= 18:
    print("El usuario es mayor de edad. ")
else:
    print("El usuario es menor de edad. ")
    